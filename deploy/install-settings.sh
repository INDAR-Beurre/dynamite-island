#!/bin/sh
# Install the Dynamite Settings control panel alongside the island.
#
#   ./deploy/install-settings.sh            # install or repair
#   ./deploy/install-settings.sh --check    # report only, change nothing
#
# Writes (absent files only — existing files are preserved, like install.sh):
#   ~/.local/share/dynamite-settings/dynamite_settings.py
#   ~/.local/bin/dynamite-settings
#   ~/.local/share/applications/dynamite-settings.desktop
#
# No build step: the app is Python 3 + GTK 4. The .desktop entry is what the
# panel's launcher uses to show the settings icon. This script never touches
# Mango's bind.conf, rule.conf, or the island's autostart wrapper.
set -eu

CHECK=0
if [ "$#" -gt 1 ]; then echo 'usage: install-settings.sh [--check]' >&2; exit 2; fi
case "${1:-}" in
    '') ;;
    --check) CHECK=1 ;;
    --help|-h) echo 'usage: install-settings.sh [--check]'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
esac

HERE=$(cd "$(dirname "$0")/.." && pwd)
APP_DIR="$HOME/.local/share/dynamite-settings"
APP="$APP_DIR/dynamite_settings.py"
LAUNCHER="$HOME/.local/bin/dynamite-settings"
DESKTOP="$HOME/.local/share/applications/dynamite-settings.desktop"
CHECKOUT_APP="$HERE/deploy/dynamite-settings/dynamite_settings.py"

note() { echo "  $*"; }
# Leave existing files intact; identical generated files need no rewrite.
write() {
    if [ "$CHECK" -eq 1 ]; then note "would install $1 if absent"; return 0; fi
    if [ -e "$1" ] || [ -L "$1" ]; then
        if printf '%s\n' "$2" | cmp -s - "$1"; then
            note "$1 already up to date"
        else
            note "$1 differs — preserving it"
        fi
        return 0
    fi
    printf '%s\n' "$2" > "$1"
}

echo "install Dynamite Settings from $HERE"
[ "$CHECK" -eq 1 ] && echo "(check only — no files will be changed)"

# --- application ---------------------------------------------------------
# Use the checkout copy when the app is bundled; otherwise repair the
# launcher and .desktop entry from the installed copy.
if [ -f "$CHECKOUT_APP" ]; then
    [ "$CHECK" -eq 0 ] && mkdir -p "$APP_DIR"
    write "$APP" "$(cat "$CHECKOUT_APP")"
else
    if [ -f "$APP" ]; then
        note "keeping the installed app at $APP"
    else
        echo "no settings app found: not bundled at deploy/dynamite-settings/ and not installed at $APP" >&2
        echo "place it there, then re-run this script" >&2
        exit 1
    fi
fi

# --- launcher ------------------------------------------------------------
LAUNCHER_SH="#!/bin/sh
# generated by deploy/install-settings.sh — runs the Dynamite Settings panel
exec python3 \"$APP\" \"\$@\""
[ "$CHECK" -eq 0 ] && mkdir -p "$HOME/.local/bin"
write "$LAUNCHER" "$LAUNCHER_SH"
if [ -e "$LAUNCHER" ] && [ ! -x "$LAUNCHER" ]; then
    [ "$CHECK" -eq 0 ] && { chmod u+x "$LAUNCHER"; note "made $LAUNCHER executable"; }
fi

# --- desktop entry -------------------------------------------------------
[ "$CHECK" -eq 0 ] && mkdir -p "$HOME/.local/share/applications"
write "$DESKTOP" "[Desktop Entry]
Type=Application
Name=Dynamite Settings
Comment=Configure the Dynamite dynamic island
Exec=$LAUNCHER
Icon=preferences-system
Terminal=false
Categories=Settings;DesktopSettings;"

# --- dependencies (report only, nothing is installed) --------------------
if command -v python3 >/dev/null 2>&1; then
    if python3 -c 'import gi; gi.require_version("Gtk","4.0"); from gi.repository import Gtk' >/dev/null 2>&1; then
        note "python3 + GTK 4 available"
    else
        note "GTK 4 Python bindings missing — on Arch: sudo pacman -S python-gobject gtk4"
    fi
else
    note "python3 missing — on Arch: sudo pacman -S python"
fi

echo
echo "Run it with:  $LAUNCHER"
echo "The panel's launcher shows the settings icon via $DESKTOP."
