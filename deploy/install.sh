#!/bin/sh
# Install the island's launcher layer without destroying existing config.
#
#   ./deploy/install.sh            # installs from this checkout
#   ./deploy/install.sh --check    # report only, change nothing
#
# Writes:
#   ~/.config/mango/dynamite-bind.conf   (spawn lines, absolute binary path)
#   appends one source line to ~/.config/mango/bind.conf if absent
#   appends the layer_rule to ~/.config/mango/rule.conf if absent
#   ~/.config/mango/scripts/dynamite_autostart.sh
#
# Adds only Dynamite's own rules and repairs its old include syntax.
set -eu

CHECK=0
if [ "$#" -gt 1 ]; then echo 'usage: install.sh [--check]' >&2; exit 2; fi
case "${1:-}" in
    '') ;;
    --check) CHECK=1 ;;
    --help|-h) echo 'usage: install.sh [--check]'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
esac

HERE=$(cd "$(dirname "$0")/.." && pwd)
BIN="$HERE/target/release/dynamite-rust"
CFG="${XDG_CONFIG_HOME:-$HOME/.config}/mango"

if [ ! -x "$BIN" ]; then
    echo "no binary at $BIN — run ./build.sh first" >&2
    exit 1
fi

note() { echo "  $*"; }
# Leave customized files intact; identical generated files need no rewrite.
write() {
    if [ "$CHECK" -eq 1 ]; then note "would install $1 if absent"; return 0; fi
    if [ -e "$1" ] || [ -L "$1" ]; then
        if printf '%s\n' "$2" | cmp -s - "$1"; then
            note "$1 already up to date"
        else
            note "$1 differs — preserving it; review the example in deploy/"
        fi
        return 0
    fi
    printf '%s\n' "$2" > "$1"
}

echo "install from $HERE"
[ "$CHECK" -eq 1 ] && echo "(check only — no files will be changed)"

# --- key bindings -------------------------------------------------------
# --check must not create anything, not even directories.
BINDS="$CFG/dynamite-bind.conf"
BIND_CONF="$CFG/bind.conf"
case "$BINDS" in
    "$HOME"/*) BINDS_TILDE="~/${BINDS#"$HOME"/}" ;;
    *) BINDS_TILDE="$BINDS" ;;
esac

# Match both spellings used by older versions, and print valid includes.
includes() {
    awk '/^[ \t]*source[ \t]*=/ {
        sub(/^[ \t]*source[ \t]*=[ \t]*/, ""); sub(/[ \t]+$/, ""); print
    }' "$BIND_CONF" | grep -qxF -e "$BINDS" -e "$BINDS_TILDE"
}
if [ -f "$BIND_CONF" ] && grep -qxF -e "source $BINDS" -e "source $BINDS_TILDE" "$BIND_CONF"; then
    note "repair old Dynamite source syntax in bind.conf"
    if [ "$CHECK" -eq 0 ]; then
        if [ -L "$BIND_CONF" ]; then
            echo "$BIND_CONF is a symlink; change its Dynamite include to 'source = $BINDS' manually" >&2
            exit 1
        fi
        PRESENT=0
        if includes; then PRESENT=1; fi
        TEMP_BINDS=$(mktemp "$CFG/.dynamite-bind.XXXXXX")
        trap 'rm -f "$TEMP_BINDS"' EXIT
        cp -p "$BIND_CONF" "$TEMP_BINDS"
        A="$BINDS" B="$BINDS_TILDE" awk -v present="$PRESENT" '
            $0 == "source " ENVIRON["A"] || $0 == "source " ENVIRON["B"] {
                if (!present++) print "source = " ENVIRON["A"]
                next
            }
            { print }
        ' "$BIND_CONF" > "$TEMP_BINDS"
        mv "$TEMP_BINDS" "$BIND_CONF"
    fi
elif [ -f "$BIND_CONF" ] && includes; then
    note "bind.conf already sources the bindings"
else
    note "append source line to bind.conf"
fi
[ "$CHECK" -eq 0 ] && mkdir -p "$CFG" "$CFG/scripts"
write "$BINDS" "# generated by deploy/install.sh — edit the path if the checkout moves
bind=SUPER,space,spawn,$BIN launcher
bind=SUPER,v,spawn,$BIN clipboard"
if [ "$CHECK" -eq 0 ] && ! { [ -f "$BIND_CONF" ] && includes; }; then
    printf '\nsource = %s\n' "$BINDS" >> "$BIND_CONF"
fi

# --- layer rule ---------------------------------------------------------
RULE='layer_rule=no_blur:1,no_shadow:1,no_animation:1,layer_name:dynamite-rust'
if [ -f "$CFG/rule.conf" ] && grep -q 'layer_name:dynamite-rust' "$CFG/rule.conf"; then
    note "rule.conf already has the dynamite-rust layer rule"
else
    [ "$CHECK" -eq 0 ] && printf '\n%s\n' "$RULE" >> "$CFG/rule.conf"
    note "append layer_rule to rule.conf"
fi

# --- autostart ----------------------------------------------------------
WRAPPER="$CFG/scripts/dynamite_autostart.sh"
if [ -e "$WRAPPER" ] || [ -L "$WRAPPER" ]; then
    note "preserving $WRAPPER"
    [ -x "$WRAPPER" ] || note "make $WRAPPER executable before adding it to autostart"
else
    write "$WRAPPER" "#!/bin/sh
# generated by deploy/install.sh — keep the panel running
ISLAND_HOME=\"$HERE\"
export ISLAND_HOME
exec \"$HERE/deploy/dynamite_autostart.sh\""
    if [ "$CHECK" -eq 0 ]; then chmod u+x "$WRAPPER"; fi
fi

echo
echo "Add to your autostart:  ~/.config/mango/scripts/dynamite_autostart.sh"
echo "Dictation needs /dev/uinput and the 'input' group — see README.md."
echo "Reload Mango (or log out and back in) for the bindings to take effect."