#!/usr/bin/env python3
"""Remove earlier Dynamite GTK and website overrides without touching other styles."""
import argparse
import os
from pathlib import Path
import re
import stat
import tempfile

PREF_LINE = b'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true); // Dynamite web theme'
GTK_IMPORT = b'@import url("../dynamite-rust/theme/gtk.css");'


def read_regular(path):
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise ValueError(f'Not a regular file: {path}')
    return path.read_bytes() if path.exists() else b''


def replace(path, old, new):
    if old == new:
        return
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as tmp:
        staged = Path(tmp.name)
        try:
            os.fchmod(tmp.fileno(), stat.S_IMODE(path.stat().st_mode))
            tmp.write(new)
            tmp.close()
            staged.replace(path)
        finally:
            staged.unlink(missing_ok=True)


def remove_theme(profile, config):
    paths = [(config / version / 'gtk.css', GTK_IMPORT) for version in ('gtk-3.0', 'gtk-4.0')]
    paths.append((profile / 'user.js', PREF_LINE))
    for path, managed in paths:
        old = read_regular(path)
        new = b''.join(line for line in old.splitlines(keepends=True) if line.strip() != managed)
        replace(path, old, new)
    path = profile / 'chrome/userContent.css'
    old = read_regular(path)
    # Keep a BOM, @charset and every rule the owner added.
    new = re.sub(rb'(?m)^@import url\([^\r\n]*\); /\* Dynamite web theme \*/\r?\n?', b'', old)
    if new == old and old.startswith(b'\xef\xbb\xbf'):
        new = b'\xef\xbb\xbf' + re.sub(rb'^@import url\([^\r\n]*\); /\* Dynamite web theme \*/\r?\n?', b'', old[3:])
    replace(path, old, new)
    # Neutralize only our generated files, including imports already cached by an app.
    for name in ('gtk.css', 'browser.css'):
        path = config / 'dynamite-rust/theme' / name
        old = read_regular(path)
        if old.startswith(b'/* Generated by Dynamite.'):
            replace(path, old, b'/* Dynamite themes now affect the island only. */\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('profile', type=Path)
    parser.add_argument('--remove', action='store_true', required=True)
    args = parser.parse_args()
    config = Path(os.environ.get('XDG_CONFIG_HOME') or Path.home() / '.config')
    try:
        remove_theme(args.profile.expanduser(), config)
    except (OSError, ValueError) as error:
        parser.exit(1, f'{error}\n')
    print('Removed Dynamite app and website overrides. Already-open apps may need a restart; none were stopped.')


if __name__ == '__main__':
    main()
