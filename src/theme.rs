//! Shared, contrast-checked colours and generated desktop/browser theme files.
use std::io::Write;
use std::path::{Path, PathBuf};

pub type Rgb = (u8, u8, u8);

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Palette {
    pub background: Rgb,
    pub surface: Rgb,
    pub foreground: Rgb,
    pub accent: Rgb,
    pub selection_text: Rgb,
}

fn luminance(rgb: Rgb) -> f64 {
    let linear = |v: u8| {
        let s = f64::from(v) / 255.0;
        if s <= 0.04045 {
            s / 12.92
        } else {
            ((s + 0.055) / 1.055).powf(2.4)
        }
    };
    0.2126 * linear(rgb.0) + 0.7152 * linear(rgb.1) + 0.0722 * linear(rgb.2)
}

fn contrast(a: Rgb, b: Rgb) -> f64 {
    let (a, b) = (luminance(a), luminance(b));
    (a.max(b) + 0.05) / (a.min(b) + 0.05)
}

fn blend(a: Rgb, b: Rgb, amount: u8) -> Rgb {
    let ch = |a: u8, b: u8| {
        ((u16::from(a) * (255 - u16::from(amount)) + u16::from(b) * u16::from(amount) + 127) / 255)
            as u8
    };
    (ch(a.0, b.0), ch(a.1, b.1), ch(a.2, b.2))
}

pub fn ink_on(background: Rgb, preferred: Rgb) -> Rgb {
    if contrast(preferred, background) >= 4.5 {
        preferred
    } else if contrast((0, 0, 0), background) >= contrast((255, 255, 255), background) {
        (0, 0, 0)
    } else {
        (255, 255, 255)
    }
}

fn readable(mut ink: Rgb, background: Rgb) -> Rgb {
    // Small steps retain the source hue even in palettes sampled from dark photos.
    while contrast(ink, background) < 4.5 && ink != (255, 255, 255) {
        ink = blend(ink, (255, 255, 255), 24);
    }
    ink
}

impl Palette {
    pub fn from_swatches(swatches: &[Rgb; 6]) -> Self {
        let mut background = swatches[0];
        while luminance(background) > 0.06 {
            background = blend(background, (0, 0, 0), 24);
        }
        let foreground = readable(
            *swatches
                .iter()
                .max_by(|a, b| luminance(**a).total_cmp(&luminance(**b)))
                .unwrap_or(&swatches[5]),
            background,
        );
        let surface = blend(background, foreground, 14);
        let foreground = readable(foreground, surface);
        let accent = readable(swatches[2], surface);
        let selection_text = ink_on(accent, background);
        Self {
            background,
            surface,
            foreground,
            accent,
            selection_text,
        }
    }

    fn browser_css(self) -> String {
        let (bg, surface, fg, accent, selected) = (
            hex(self.background),
            hex(self.surface),
            hex(self.foreground),
            hex(self.accent),
            hex(self.selection_text),
        );
        // Keep layout, media, gradients, and browser UI outside this override.
        format!(
            r#"/* Generated by Dynamite. */
@-moz-document url-prefix("http://"), url-prefix("https://") {{
    html {{ color-scheme: dark !important; }}
    html, body {{ background-color: {bg} !important; color: {fg} !important; }}
    :is(main, article, section, header, footer, nav, aside, dialog, div, table, td, th, pre, code) {{
        background-color: {bg} !important;
        color: {fg} !important;
    }}
    :is(input, textarea, select, button) {{
        background-color: {surface} !important;
        color: {fg} !important;
        accent-color: {accent} !important;
    }}
    :is(p, li, label, h1, h2, h3, h4, h5, h6, span, strong, em, small) {{ color: {fg} !important; }}
    a:any-link, a:any-link *:not(svg):not(svg *) {{ color: {accent} !important; }}
    ::selection {{ background-color: {accent} !important; color: {selected} !important; }}
}}
"#
        )
    }

    fn gtk_css(self) -> String {
        let (bg, surface, fg, accent, selected) = (
            hex(self.background),
            hex(self.surface),
            hex(self.foreground),
            hex(self.accent),
            hex(self.selection_text),
        );
        format!("/* Generated by Dynamite. Select a theme in the shell to update. */\n\
@define-color theme_bg_color {bg};\n@define-color theme_base_color {bg};\n\
@define-color theme_fg_color {fg};\n@define-color theme_text_color {fg};\n\
@define-color theme_selected_bg_color {accent};\n@define-color theme_selected_fg_color {selected};\n\
@define-color window_bg_color {bg};\n@define-color window_fg_color {fg};\n\
@define-color view_bg_color {bg};\n@define-color view_fg_color {fg};\n\
@define-color headerbar_bg_color {surface};\n@define-color headerbar_fg_color {fg};\n\
@define-color card_bg_color {surface};\n@define-color card_fg_color {fg};\n\
@define-color dialog_bg_color {surface};\n@define-color dialog_fg_color {fg};\n\
@define-color popover_bg_color {surface};\n@define-color popover_fg_color {fg};\n\
@define-color accent_color {accent};\n@define-color accent_bg_color {accent};\n\
@define-color accent_fg_color {selected};\n\
window, dialog, .background {{ background-color: {bg}; color: {fg}; }}\n\
entry, textview text, treeview.view {{ background-color: {surface}; color: {fg}; }}\n\
selection {{ background-color: {accent}; color: {selected}; }}\n\
*:link {{ color: {accent}; }}\n")
    }
}

fn hex(c: Rgb) -> String {
    format!("#{:02x}{:02x}{:02x}", c.0, c.1, c.2)
}

pub fn config_home() -> PathBuf {
    std::env::var_os("XDG_CONFIG_HOME")
        .filter(|s| !s.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join(".config")
        })
}

pub fn atomic_write(path: &Path, data: &[u8]) -> std::io::Result<()> {
    let parent = path
        .parent()
        .ok_or_else(|| std::io::Error::other("no parent directory"))?;
    std::fs::create_dir_all(parent)?;
    let tmp = parent.join(format!(
        ".dynamite-{}-{}.tmp",
        std::process::id(),
        path.file_name().unwrap_or_default().to_string_lossy()
    ));
    let permissions = match std::fs::symlink_metadata(path) {
        Ok(meta) if meta.is_file() => Some(meta.permissions()),
        Ok(_) => return Err(std::io::Error::other("expected a regular file")),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e),
    };
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&tmp)?;
    let result = (|| {
        if let Some(permissions) = permissions {
            f.set_permissions(permissions)?;
        }
        f.write_all(data)?;
        f.sync_all()?;
        std::fs::rename(&tmp, path)
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(tmp);
    }
    result
}

const GTK_IMPORT: &str = "@import url(\"../dynamite-rust/theme/gtk.css\");";

/// Dedicated files plus one import preserve the user's existing GTK stylesheet.
pub fn apply_at(config: &Path, palette: Palette) -> Result<(), String> {
    let write = |path: &Path, data: &[u8]| {
        atomic_write(path, data).map_err(|e| format!("theme write {}: {e}", path.display()))
    };
    let theme_dir = config.join("dynamite-rust/theme");
    write(&theme_dir.join("gtk.css"), palette.gtk_css().as_bytes())?;
    for version in ["gtk-3.0", "gtk-4.0"] {
        let path = config.join(version).join("gtk.css");
        let old = match std::fs::read_to_string(&path) {
            Ok(s) => s,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
            Err(e) => return Err(format!("theme read {}: {e}", path.display())),
        };
        if !old.lines().any(|line| line.trim() == GTK_IMPORT) {
            if path.exists() {
                let backup = path.with_file_name("gtk.css.before-dynamite");
                if !backup.exists() {
                    std::fs::copy(&path, backup).map_err(|e| e.to_string())?;
                }
            }
            write(&path, format!("{GTK_IMPORT}\n{old}").as_bytes())?;
        }
    }
    write(
        &theme_dir.join("browser.css"),
        palette.browser_css().as_bytes(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn even_dark_photo_palettes_have_readable_text_links_and_selection() {
        for swatches in [
            [(0, 0, 0); 6],
            [(255, 255, 255); 6],
            [
                (2, 10, 18),
                (4, 22, 40),
                (13, 70, 128),
                (6, 5, 19),
                (32, 27, 102),
                (116, 115, 112),
            ],
        ] {
            let p = Palette::from_swatches(&swatches);
            assert!(contrast(p.foreground, p.surface) >= 4.5);
            assert!(contrast(p.accent, p.surface) >= 4.5);
            assert!(contrast(p.selection_text, p.accent) >= 4.5);
            assert!(contrast(ink_on(p.accent, (11, 27, 58)), p.accent) >= 4.5);
        }
    }

    #[test]
    fn gtk_import_is_idempotent_and_keeps_existing_styles() {
        let root = std::env::temp_dir().join(format!("dynamite-theme-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("gtk-3.0")).unwrap();
        let path = root.join("gtk-3.0/gtk.css");
        std::fs::write(&path, "button { border-radius: 7px; }\n").unwrap();
        let first = Palette::from_swatches(&[(20, 25, 30); 6]);
        apply_at(&root, first).unwrap();
        let second = Palette::from_swatches(&[(30, 20, 45); 6]);
        apply_at(&root, second).unwrap();
        let css = std::fs::read_to_string(path).unwrap();
        assert_eq!(css.matches(GTK_IMPORT).count(), 1);
        assert!(css.contains("button { border-radius: 7px; }"));
        assert_eq!(
            std::fs::read_to_string(root.join("dynamite-rust/theme/browser.css")).unwrap(),
            second.browser_css()
        );
        assert_eq!(
            std::fs::read_to_string(root.join("gtk-3.0/gtk.css.before-dynamite")).unwrap(),
            "button { border-radius: 7px; }\n"
        );
        std::fs::remove_dir_all(root).unwrap();
    }
}
