static ICON_FONT: OnceLock<Option<Font>> = OnceLock::new();

fn icon_font() -> Option<&'static Font> {
    ICON_FONT
        .get_or_init(|| {
            // iter116 (Lane A): embedded 15-glyph subset first (3,904 B,
            // ~64 kB parse); full disk font as fallback. See main.rs.
            if let Ok(f) = Font::from_bytes(
                include_bytes!("icons/MaterialSymbolsRounded-Island.ttf").to_vec(),
                FontSettings::default(),
            ) {
                return Some(f);
            }
            let home = std::env::var_os("HOME").map(std::path::PathBuf::from)?;
            let path = home.join(".local/share/fonts/MaterialSymbolsRounded.ttf");
            let bytes = std::fs::read(path).ok()?;
            Font::from_bytes(bytes, FontSettings::default()).ok()
        })
        .as_ref()
}

// ---------------------------------------------------------------------------
// Uptime: "Up 3 h 34 min" (video style). Empty input => read /proc/uptime.
// ---------------------------------------------------------------------------
pub fn uptime_string() -> String {
    let secs = std::fs::read_to_string("/proc/uptime")
        .ok()
        .and_then(|s| s.split_whitespace().next().map(str::to_string))
        .and_then(|s| s.parse::<f64>().ok())
        .unwrap_or(0.0) as u64;
    let h = secs / 3600;
    let m = (secs % 3600) / 60;
    if h > 0 {
        format!("Up {h} h {m:02} min")
    } else {
        format!("Up {m} min")
    }
}

// ---------------------------------------------------------------------------
// Pixel helpers — same style as main.rs: premultiplied Argb8888 canvas,
// BGRA byte order, src-over onto the (opaque) black panel.
//
// r1d §22 (2x panels): `canvas` is w x h DEVICE px and every public
// function here takes LOGICAL coords; the scale is w/PANEL_W, so the
// same code renders 1x (w == PANEL_W) or 2x (w == PANEL_W*2) and the
// anti-aliasing band is one DEVICE px either way. Callers therefore
// pass the canvas dimensions and logical geometry, nothing else.
// ---------------------------------------------------------------------------
fn scale_of(w: u32) -> f32 {
    w as f32 / PANEL_W as f32
}

/// Blend one already-device-space pixel.
fn blend_px(canvas: &mut [u8], w: u32, h: u32, x: i32, y: i32, rgb: [u8; 3], cov: f32) {
    if x < 0 || y < 0 || x >= w as i32 || y >= h as i32 || cov <= 0.0 {
        return;
    }
    let c = cov.clamp(0.0, 1.0);
    let i = ((y as u32 * w + x as u32) * 4) as usize;
    // rgb is [R, G, B]; canvas bytes are [B, G, R, A].
    canvas[i] = (rgb[2] as f32 * c + canvas[i] as f32 * (1.0 - c)) as u8;
    canvas[i + 1] = (rgb[1] as f32 * c + canvas[i + 1] as f32 * (1.0 - c)) as u8;
    canvas[i + 2] = (rgb[0] as f32 * c + canvas[i + 2] as f32 * (1.0 - c)) as u8;
    canvas[i + 3] = 255;
}

fn fill_circle(canvas: &mut [u8], w: u32, h: u32, cx: f32, cy: f32, r: f32, rgb: [u8; 3]) {
    let s = scale_of(w);
    let (cx, cy, r) = (cx * s, cy * s, r * s);
    let x0 = (cx - r - 1.0).floor() as i32;
    let x1 = (cx + r + 1.0).ceil() as i32;
    let y0 = (cy - r - 1.0).floor() as i32;
    let y1 = (cy + r + 1.0).ceil() as i32;
    for y in y0..y1 {
        for x in x0..x1 {
            let dx = x as f32 + 0.5 - cx;
            let dy = y as f32 + 0.5 - cy;
            let d = (dx * dx + dy * dy).sqrt() - r;
            blend_px(canvas, w, h, x, y, rgb, (0.5 - d).clamp(0.0, 1.0));
        }
    }
}

fn fill_rect(canvas: &mut [u8], w: u32, h: u32, x0: f32, y0: f32, x1: f32, y1: f32, rgb: [u8; 3]) {
    let s = scale_of(w);
    let (x0, y0, x1, y1) = (x0 * s, y0 * s, x1 * s, y1 * s);
    for y in (y0.floor() as i32)..(y1.ceil() as i32) {
        for x in (x0.floor() as i32)..(x1.ceil() as i32) {
            let cov_x = (x1.min(x as f32 + 1.0) - x0.max(x as f32)).clamp(0.0, 1.0);
            let cov_y = (y1.min(y as f32 + 1.0) - y0.max(y as f32)).clamp(0.0, 1.0);
            blend_px(canvas, w, h, x, y, rgb, cov_x * cov_y);
        }
    }
}

/// Ring segment: circle outline of radius `r`, stroke `thick`, with a wedge
/// of half-angle `gap_half` around `gap_angle` (radians, atan2 convention)
/// left open. `gap_half` = PI draws nothing; 0.0 draws a full ring.
fn ring_segment(
    canvas: &mut [u8],
    w: u32,
    h: u32,
    cx: f32,
    cy: f32,
    r: f32,
    thick: f32,
    gap_angle: f32,
    gap_half: f32,
    rgb: [u8; 3],
) {
    let s = scale_of(w);
    let (cx, cy, r, thick) = (cx * s, cy * s, r * s, thick * s);
    let x0 = (cx - r - thick).floor() as i32;
    let x1 = (cx + r + thick).ceil() as i32;
    let y0 = (cy - r - thick).floor() as i32;
    let y1 = (cy + r + thick).ceil() as i32;
    for y in y0..y1 {
        for x in x0..x1 {
            let dx = x as f32 + 0.5 - cx;
            let dy = y as f32 + 0.5 - cy;
            let dist = (dx * dx + dy * dy).sqrt();
            let mut da = (dy.atan2(dx) - gap_angle).abs();
            if da > std::f32::consts::PI {
                da = 2.0 * std::f32::consts::PI - da;
            }
            if da < gap_half {
                continue;
            }
            let sdf = (dist - r).abs() - thick / 2.0;
            blend_px(canvas, w, h, x, y, rgb, (0.5 - sdf).clamp(0.0, 1.0));
        }
    }
}

fn fill_triangle(
    canvas: &mut [u8],
    w: u32,
    h: u32,
    (ax, ay): (f32, f32),
    (bx, by): (f32, f32),
    (cx, cy): (f32, f32),
    rgb: [u8; 3],
) {
    // Edge-function fill, 1px AA on the boundary via coverage estimate.
    let s = scale_of(w);
    let ((ax, ay), (bx, by), (cx, cy)) =
        ((ax * s, ay * s), (bx * s, by * s), (cx * s, cy * s));
    let x0 = ax.min(bx).min(cx).floor() as i32 - 1;
    let x1 = ax.max(bx).max(cx).ceil() as i32 + 1;
    let y0 = ay.min(by).min(cy).floor() as i32 - 1;
    let y1 = ay.max(by).max(cy).ceil() as i32 + 1;
    let edge = |px: f32, py: f32, x1: f32, y1: f32, x2: f32, y2: f32| -> f32 {
        (px - x1) * (y2 - y1) - (py - y1) * (x2 - x1)
    };
    let area = edge(ax, ay, bx, by, cx, cy);
    if area == 0.0 {
        return;
    }
    for y in y0..y1 {
        for x in x0..x1 {
            let px = x as f32 + 0.5;
            let py = y as f32 + 0.5;
            let w0 = edge(px, py, bx, by, cx, cy) / area;
            let w1 = edge(px, py, cx, cy, ax, ay) / area;
            let w2 = edge(px, py, ax, ay, bx, by) / area;
            let inside = w0.min(w1).min(w2);
            if inside >= 0.0 {
                blend_px(canvas, w, h, x, y, rgb, 1.0);
            } else if inside > -0.06 {
                blend_px(canvas, w, h, x, y, rgb, (1.0 + inside / 0.06).clamp(0.0, 1.0));
            }
        }
    }
}

// ---------------------------------------------------------------------------
// Text — same layout/blit approach as main.rs (duplicated: main.rs's
// helpers are private and this module must stay drop-in).
// ---------------------------------------------------------------------------
struct TextRow {
    glyphs: Vec<(fontdue::Metrics, Vec<u8>)>,
    width: f32,
    ascent: f32,
}

fn layout_text(font: &Font, text: &str, px: f32) -> TextRow {
    let mut glyphs = Vec::new();
    let mut width = 0.0f32;
    for ch in text.chars() {
        let (m, cov) = font.rasterize(ch, px);
        width += m.advance_width;
        glyphs.push((m, cov));
    }
    let ascent = font
        .horizontal_line_metrics(px)
        .map(|lm| lm.ascent)
        .unwrap_or(px);
    TextRow {
        glyphs,
        width,
        ascent,
    }
}

fn blit_glyph(
    canvas: &mut [u8],
    w: u32,
    h: u32,
    m: &fontdue::Metrics,
    cov: &[u8],
    x0: i32,
    y0: i32,
    rgb: [u8; 3],
) {
    for gy in 0..m.height as i32 {
        for gx in 0..m.width as i32 {
            let c = cov[gy as usize * m.width + gx as usize] as f32 / 255.0;
            if c > 0.0 {
                blend_px(canvas, w, h, x0 + gx, y0 + gy, rgb, c);
            }
        }
    }
}

/// Draw `text` centred on `cx`, with its top edge at `top_y`.
fn draw_text_centred(
    canvas: &mut [u8],
    w: u32,
    h: u32,
    font: &Font,
    text: &str,
    px: f32,
    cx: f32,
    top_y: f32,
    rgb: [u8; 3],
) {
    let s = scale_of(w);
    let row = layout_text(font, text, px * s);
    let baseline = top_y * s + row.ascent;
    let mut pen = cx * s - row.width / 2.0;
    for (m, cov) in &row.glyphs {
        let gx0 = (pen + m.xmin as f32).round() as i32;
        let gy0 = (baseline - m.ymin as f32 - m.height as f32).round() as i32;
        blit_glyph(canvas, w, h, m, cov, gx0, gy0, rgb);
        pen += m.advance_width;
    }
}

/// Draw one Material Symbols glyph so its visual centre lands on (cx, cy),
/// in the given colour (white for the four grey discs, LOCK_GLYPH for the
/// centre lock — the video's lock is dark navy on pale periwinkle).
fn draw_icon_glyph(
    canvas: &mut [u8],
    w: u32,
    h: u32,
    icon: &Font,
    ch: char,
    px: f32,
    cx: f32,
    cy: f32,
    rgb: [u8; 3],
) {
    let s = scale_of(w);
    let (m, cov) = icon.rasterize(ch, px * s);
    if m.width == 0 || m.height == 0 {
        return;
    }
    let gx0 = (cx * s - m.width as f32 / 2.0).round() as i32;
    let gy0 = (cy * s - m.height as f32 / 2.0).round() as i32;
    blit_glyph(canvas, w, h, &m, &cov, gx0, gy0, rgb);
}

