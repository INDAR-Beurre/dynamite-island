// iter36 a6b: power buttons wired for real (via logind; Lock via swaylock since iter39).
//
// Disc order left->right: moon, logout, lock (centre), refresh, power.
// Mapping: the moon reads as sleep (suspend); refresh reads as restart
// (reboot). Only Lock executes on click (`swaylock -f -c 000000`);
// the other four are destructive, so the press arm logs their exact
// command (command-path verification) and does NOT run them
// unannounced. The other four go through elogind loginctl ONLY (iter132
// B2: this box is Artix — there is NO systemctl, so the old
// `systemctl suspend/reboot/poweroff` strings were dead; loginctl
// suspend/reboot/poweroff verified via `loginctl --dry-run`, exit 0).
// Logout needs the session id: `loginctl terminate-session` with no ID
// fails (help: `terminate-session ID...`; fake-ID probe exits 1), so
// it is `loginctl terminate-session $XDG_SESSION_ID` — the island runs
// with XDG_SESSION_ID=3 and spawn_exec runs via sh -c, so it expands.
// Lock spawns swaylock directly (iter38: loginctl lock-session is a
// no-op under mango - no logind Lock listener; bind.conf:14 already
// uses `swaylock -f -c 000000`).
// ---------------------------------------------------------------------------

/// Button centres (panel-local) + hit radius (disc R 21 + 2 slack).
/// Disc geometry (centre-x list, centre-y, radius) for a panel of
/// w x h — r1d §17 fraction-derived, so any panel size keeps the
/// reference layout.
fn disc_geometry(w: u32, h: u32) -> (f32, f32) {
    let row_cy = DISC_CY_FRAC * h as f32;
    let btn_r = 0.5 * DISC_DIAM_FRAC * w as f32;
    (row_cy, btn_r)
}

pub fn button_centres() -> [(f32, f32); 5] {
    let (row_cy, _) = disc_geometry(PANEL_W, PANEL_H);
    DISC_CX_FRACS.map(|f| (f * PANEL_W as f32, row_cy))
}

pub fn button_hit(px: f32, py: f32) -> Option<usize> {
    let (_, btn_r) = disc_geometry(PANEL_W, PANEL_H);
    for (i, &(cx, cy)) in button_centres().iter().enumerate() {
        if (px - cx).abs() <= btn_r + 2.0 && (py - cy).abs() <= btn_r + 2.0 {
            return Some(i);
        }
    }
    None
}

/// (label, exact command) for disc `i`.
pub fn action_command(i: usize) -> (&'static str, &'static str) {
    match i {
        0 => ("suspend", "loginctl suspend"),
        1 => ("logout", "loginctl terminate-session $XDG_SESSION_ID"),
        2 => ("lock", "swaylock -f -c 000000"),
        3 => ("reboot", "loginctl reboot"),
        _ => ("poweroff", "loginctl poweroff"),
    }
}
