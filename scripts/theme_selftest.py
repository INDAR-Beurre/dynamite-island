#!/usr/bin/env python3
"""Check removal of earlier app/web hooks and that theme changes stay island-only."""
import importlib.util
import os
from pathlib import Path
import stat
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('waterfox_theme', ROOT / 'deploy/waterfox-theme.py')
setup = importlib.util.module_from_spec(spec)
spec.loader.exec_module(setup)


def check_removal(root):
    profile, config = root / 'profile', root / 'config with spaces'
    (profile / 'chrome').mkdir(parents=True)
    managed = b'@import url("file:///config/browser.css"); /* Dynamite web theme */\n'
    owner_pref = b'user_pref("browser.shell.checkDefaultBrowser", false);\n'
    css = profile / 'chrome/userContent.css'
    prefs = profile / 'user.js'
    for prefix in (b'', b'\xef\xbb\xbf', b'@charset "UTF-8";\n', b'\xef\xbb\xbf@charset "UTF-8";\r\n'):
        original = prefix + b'@import url("owner.css");\n.fixture { color: red; }\n'
        css.write_bytes(prefix + managed + original[len(prefix):])
        css.chmod(0o640)
        prefs.write_bytes(owner_pref + setup.PREF_LINE + b'\n')
        for version in ('gtk-3.0', 'gtk-4.0'):
            path = config / version / 'gtk.css'
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(setup.GTK_IMPORT + b'\n/* Owner style */\nlabel { color: red; }\n')
        generated = config / 'dynamite-rust/theme'
        generated.mkdir(parents=True, exist_ok=True)
        for name in ('gtk.css', 'browser.css'):
            (generated / name).write_bytes(b'/* Generated by Dynamite. old override */\n* { color: red; }\n')
        setup.remove_theme(profile, config)
        setup.remove_theme(profile, config)
        assert css.read_bytes() == original, 'owner CSS/BOM/charset changed'
        assert stat.S_IMODE(css.stat().st_mode) == 0o640
        assert prefs.read_bytes() == owner_pref
        for version in ('gtk-3.0', 'gtk-4.0'):
            assert (config / version / 'gtk.css').read_bytes() == b'/* Owner style */\nlabel { color: red; }\n'
        for name in ('gtk.css', 'browser.css'):
            assert (generated / name).read_bytes() == b'/* Dynamite themes now affect the island only. */\n'
    # Do not neutralize styles that were not generated by this project.
    (generated / 'browser.css').write_bytes(b'/* Owner CSS */\nbody { color: blue; }\n')
    setup.remove_theme(profile, config)
    assert (generated / 'browser.css').read_bytes().startswith(b'/* Owner CSS */')
    css.unlink()
    target = root / 'owner-target.css'
    target.write_bytes(b'keep me')
    css.symlink_to(target)
    try:
        setup.remove_theme(profile, config)
    except ValueError:
        pass
    else:
        raise AssertionError('symlink must be refused')
    assert target.read_bytes() == b'keep me'
    empty = root / 'absent'
    setup.remove_theme(empty / 'profile', empty / 'config')
    assert not empty.exists(), 'cleanup created missing files'
    print('PASS: cleanup preserves owner rules, modes, BOM/charset; repeat-safe; rejects symlinks')


def check_island_only(root):
    config = root / 'theme-config'
    library = config / 'dynamite-rust/library'
    library.mkdir(parents=True)
    (library / 'themes.json').write_text('''{"themes": {
"green": {"palette": ["#2D353B","#A7C080","#E69875","#DBBC7F","#7FBBB3","#D699B6"],"wallpapers": []},
"pink": {"palette": ["#272D2D","#576365","#80416C","#DD97AF","#483E66","#F7F3F3"],"wallpapers": []}}}''')
    for version in ('gtk-3.0', 'gtk-4.0'):
        path = config / version / 'gtk.css'
        path.parent.mkdir()
        path.write_bytes(b'/* Owner style */\n')
    before = {p.relative_to(config): p.read_bytes() for p in config.rglob('*') if p.is_file()}
    runtime = root / 'runtime'
    runtime.mkdir(mode=0o700)
    env = dict(os.environ, XDG_CONFIG_HOME=str(config), XDG_RUNTIME_DIR=str(runtime))
    for name in ('green', 'pink'):
        subprocess.run([str(ROOT / 'target/release/dynamite-rust'), '--apply-theme', name],
                       env=env, check=True, capture_output=True, timeout=8)
        after = {p.relative_to(config): p.read_bytes() for p in config.rglob('*') if p.is_file()}
        assert set(after) - set(before) == {Path('dynamite-rust/config.conf')}
        assert all(after[p] == content for p, content in before.items())
        assert f'theme={name}' in (config / 'dynamite-rust/config.conf').read_text()
    print('PASS: applying two palettes writes only the island config, with no GTK or browser output')


def main():
    with tempfile.TemporaryDirectory(prefix='dynamite-theme-check-') as directory:
        root = Path(directory)
        check_removal(root)
        check_island_only(root)


if __name__ == '__main__':
    main()
